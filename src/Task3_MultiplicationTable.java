public class Task3_MultiplicationTable {
    public static void main(String[] args) {
        int number = 5;

        System.out.println("Multiplication Table for " + number + ":");

        // Loop from 1 to 10
        for (int i = 1; i <= 10; i++) {
            int result = number * i;
            System.out.println(number + " x " + i + " = " + result);
        }
    }
}










